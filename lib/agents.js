const COMMON = [
  { k: ['안녕', '반가', '하이', 'hello', 'hi'], a: (ag) => [`안녕하세요! ${ag.title} ${ag.name}입니다. 무엇을 도와드릴까요?`] },
  { k: ['고마', '감사', '수고'], a: () => ['별말씀을요! 또 필요하면 불러 주세요.', '감사합니다. 맡겨 주셔서 든든하네요.'] },
  { k: ['뭐해', '뭐 해', '진행', '상황', '어때'], a: (ag) => [ag.idle[0]] },
];

export function getAgent(id) {
  return AGENTS.find((a) => a.id === id) || null;
}

function pick(list, rand) {
  return list[Math.floor(rand() * list.length) % list.length];
}

export function agentReply(agent, text, rand = Math.random) {
  const t = String(text).toLowerCase();
  for (const r of agent.rules) if (r.k.some((k) => t.includes(k))) return pick(r.a, rand);
  for (const r of COMMON) if (r.k.some((k) => t.includes(k))) return pick(r.a(agent), rand);
  return pick(agent.idle, rand);
}

export function taskAck(agent, title, rand = Math.random) {
  return pick([
    `"${title}" 업무 확인했습니다. 바로 시작할게요.`,
    `네, "${title}" 맡겠습니다. 끝나면 보고드릴게요.`,
  ], rand);
}

export function taskReport(agent, title, rand = Math.random) {
  return pick([
    `"${title}" 완료했습니다. 확인 부탁드려요.`,
    `"${title}" 마무리했어요. 추가로 필요한 것 있으면 말씀 주세요.`,
  ], rand);
}

// 업무 소요 시간(초). 데모라서 짧게 잡는다.
export function taskDuration(rand = Math.random) {
  return 20 + Math.floor(rand() * 40);
}
